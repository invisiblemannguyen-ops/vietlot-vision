/*
# Lottery Analytics & Prediction Schema

## Purpose
Stores rolling 50-draw historical results per Vietnamese lottery station,
predictions generated by the weighted time-decay model, evaluation results
(hit rate %, payout ROI), and auto-tuning parameter logs. Single-tenant app
(no auth) so data is intentionally shared/public.

## New Tables
1. `lottery_stations` — Vietnamese lottery stations (XSMB, XSMN, XSMT).
   - id (text, PK, station code e.g. "xsmb","hcm","danang")
   - name (text, display name)
   - region (text: "XSMB" | "XSMN" | "XSMT")
   - w1, w2, w3 (numeric, decay weights; default 5,3,2)
   - tuned_at (timestamptz, last auto-tune run)
   - created_at (timestamptz)

2. `lottery_draws` — rolling 50-draw history per station.
   - id (uuid PK)
   - station_id (text FK -> lottery_stations.id)
   - draw_date (date, the draw day)
   - special_prize (text, 5-6 digit special prize number)
   - lo_numbers (text[], 2-digit "lo" numbers drawn that day)
   - created_at (timestamptz)
   - unique (station_id, draw_date)

3. `lottery_predictions` — Stage 1 predictions (PENDING) and Stage 2 evaluation.
   - id (uuid PK)
   - station_id (text FK)
   - target_date (date, draw date the prediction targets)
   - prediction_type (text: "bao_lo_2d","bao_lo_3d","dau_duoi","doc_dac","xien_2","xien_3")
   - numbers (text[], the predicted numbers)
   - score_data (jsonb, digit scores Hundreds/Tens/Ones + bucket breakdown)
   - weights (jsonb, w1/w2/w3 used to generate)
   - status (text: "PENDING" | "EVALUATED")
   - hits (text[], numbers that hit the actual draw)
   - hit_count (int)
   - total_predicted (int)
   - hit_rate (numeric %)
   - payout (numeric, calculated payout)
   - cost (numeric, staking cost)
   - roi (numeric %, return on investment)
   - evaluated_at (timestamptz)
   - created_at (timestamptz)

4. `lottery_tuning_logs` — auto-tuning / self-learning audit trail.
   - id (uuid PK)
   - station_id (text FK)
   - evaluated_count (int, number of evaluated draws that triggered tuning)
   - old_weights (jsonb)
   - new_weights (jsonb)
   - best_win_rate (numeric %)
   - candidates_tried (int)
   - backtest_window (int, number of draws in backtest)
   - created_at (timestamptz)

## Security
- Single-tenant, no auth: RLS enabled on all tables.
- CRUD granted to anon + authenticated (data intentionally public/shared).
- USING (true) is correct here because there is no per-user isolation.
*/

CREATE TABLE IF NOT EXISTS lottery_stations (
  id text PRIMARY KEY,
  name text NOT NULL,
  region text NOT NULL CHECK (region IN ('XSMB','XSMN','XSMT')),
  w1 numeric NOT NULL DEFAULT 5,
  w2 numeric NOT NULL DEFAULT 3,
  w3 numeric NOT NULL DEFAULT 2,
  tuned_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS lottery_draws (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  station_id text NOT NULL REFERENCES lottery_stations(id) ON DELETE CASCADE,
  draw_date date NOT NULL,
  special_prize text,
  lo_numbers text[] NOT NULL DEFAULT '{}',
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (station_id, draw_date)
);

CREATE TABLE IF NOT EXISTS lottery_predictions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  station_id text NOT NULL REFERENCES lottery_stations(id) ON DELETE CASCADE,
  target_date date NOT NULL,
  prediction_type text NOT NULL CHECK (prediction_type IN ('bao_lo_2d','bao_lo_3d','dau_duoi','doc_dac','xien_2','xien_3')),
  numbers text[] NOT NULL DEFAULT '{}',
  score_data jsonb NOT NULL DEFAULT '{}'::jsonb,
  weights jsonb NOT NULL DEFAULT '{}'::jsonb,
  status text NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','EVALUATED')),
  hits text[] NOT NULL DEFAULT '{}',
  hit_count integer NOT NULL DEFAULT 0,
  total_predicted integer NOT NULL DEFAULT 0,
  hit_rate numeric NOT NULL DEFAULT 0,
  payout numeric NOT NULL DEFAULT 0,
  cost numeric NOT NULL DEFAULT 0,
  roi numeric NOT NULL DEFAULT 0,
  evaluated_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS lottery_tuning_logs (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  station_id text NOT NULL REFERENCES lottery_stations(id) ON DELETE CASCADE,
  evaluated_count integer NOT NULL,
  old_weights jsonb NOT NULL,
  new_weights jsonb NOT NULL,
  best_win_rate numeric NOT NULL DEFAULT 0,
  candidates_tried integer NOT NULL DEFAULT 0,
  backtest_window integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- Indexes for common queries
CREATE INDEX IF NOT EXISTS idx_draws_station_date ON lottery_draws (station_id, draw_date DESC);
CREATE INDEX IF NOT EXISTS idx_predictions_station_status ON lottery_predictions (station_id, status, target_date DESC);
CREATE INDEX IF NOT EXISTS idx_predictions_station_type ON lottery_predictions (station_id, prediction_type, target_date DESC);
CREATE INDEX IF NOT EXISTS idx_tuning_station ON lottery_tuning_logs (station_id, created_at DESC);

-- RLS
ALTER TABLE lottery_stations ENABLE ROW LEVEL SECURITY;
ALTER TABLE lottery_draws ENABLE ROW LEVEL SECURITY;
ALTER TABLE lottery_predictions ENABLE ROW LEVEL SECURITY;
ALTER TABLE lottery_tuning_logs ENABLE ROW LEVEL SECURITY;

-- Grants (single-tenant, no auth)
GRANT SELECT, INSERT, UPDATE, DELETE ON lottery_stations TO anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON lottery_draws TO anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON lottery_predictions TO anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON lottery_tuning_logs TO anon, authenticated;

-- Policies: intentionally public/shared single-tenant data
DROP POLICY IF EXISTS "anon_rw_stations" ON lottery_stations;
CREATE POLICY "anon_rw_stations" ON lottery_stations
  TO anon, authenticated USING (true) WITH CHECK (true);
DROP POLICY IF EXISTS "anon_rw_draws" ON lottery_draws;
CREATE POLICY "anon_rw_draws" ON lottery_draws
  TO anon, authenticated USING (true) WITH CHECK (true);
DROP POLICY IF EXISTS "anon_rw_predictions" ON lottery_predictions;
CREATE POLICY "anon_rw_predictions" ON lottery_predictions
  TO anon, authenticated USING (true) WITH CHECK (true);
DROP POLICY IF EXISTS "anon_rw_tuning" ON lottery_tuning_logs;
CREATE POLICY "anon_rw_tuning" ON lottery_tuning_logs
  TO anon, authenticated USING (true) WITH CHECK (true);

